//! Each file in `tests/` is a module here instead of its own test binary:
//! one link instead of ~180, and on macOS one first-launch security scan
//! instead of one per binary. nextest still runs every test in its own
//! process, so environment and working-directory changes stay isolated.
//! Test names start with the file name (`dev300_cli_sync_followups_test::...`);
//! select a file with `-E 'test(/^dev300_/)'` or a plain substring.
//!
//! `nextest_guard_test` and `performance_test` stay separate binaries.
//! New test files must be added below (Cargo.toml sets `autotests = false`).

